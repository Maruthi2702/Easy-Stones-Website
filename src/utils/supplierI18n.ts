export const STRINGS: Record<Lang, Strings> = { en, pt, es, it, tr, ms, hi, vi, zh };

/** One string in `lang` (English when the language or key is missing), placeholders filled. */
export function t(lang: string, key: StringKey, vars: Record<string, string | number> = {}): string {
  const table = STRINGS[(LANGUAGE_CODES.includes(lang) ? lang : 'en') as Lang] || en;
  const raw = table[key] ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => (vars[k] !== undefined ? String(vars[k]) : m));
}

/** A rejection or new-photo reason in `lang`. */
export const reasonText = (lang: string, decision: string, reason: string | undefined) =>
  reason ? t(lang, `${decision === 'retake' ? 'p' : 'r'}_${reason}` as StringKey) : '';
